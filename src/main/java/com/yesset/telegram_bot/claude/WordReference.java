package com.yesset.telegram_bot.claude;

import com.fasterxml.jackson.annotation.JsonPropertyDescription;

import java.util.List;

public record WordReference(
        @JsonPropertyDescription("Часть речи на русском языке, например: глагол, существительное, прилагательное")
        String partOfSpeech,

        @JsonPropertyDescription("Однокоренные слова / словообразовательная семья — прежде всего для глаголов: формы с разными приставками, меняющими вид или значение слова (например, для 'играть': выиграть, проиграть, сыграть, поиграть, отыграть). 4-10 самых употребимых форм с кратким пояснением значения НА КАЗАХСКОМ для каждой. Пустой список, если для этой части речи это неприменимо")
        List<WordForm> relatedWords,

        @JsonPropertyDescription("6-12 самых полезных грамматических форм этого слова: для глагола — спряжение по лицам и временам (настоящее, прошедшее, будущее), повелительное наклонение, вид (совершенный/несовершенный); для существительного — падежные формы и множественное число; для прилагательного — степени сравнения. С кратким пояснением НА КАЗАХСКОМ для каждой формы")
        List<WordForm> forms,

        @JsonPropertyDescription("Короткое дополнительное примечание НА КАЗАХСКОМ ЯЗЫКЕ, если уместно (например, устойчивое выражение с этим словом). Пустая строка, если добавить нечего")
        String note
) {
}